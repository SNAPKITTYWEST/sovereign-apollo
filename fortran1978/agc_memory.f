C     AGC_MEMORY.F  — Erasable/Fixed, 1's complement, channels (src/agc/memory.ts)
      BLOCK DATA AGMMEM
      INTEGER IERAS, IFIXED, EB, FB, ICHAN
      COMMON /AGCMEM/ IERAS(2048), IFIXED(36864), EB, FB, ICHAN(0:77)
      DATA IERAS/2048*0/, IFIXED/36864*0/, EB/0/, FB/0/, ICHAN/78*0/
      END
C     I15ADD — 1's complement end-around carry (DOCUMENTED R-393)
C     Returns (A+B) masked 15 bits with end-around carry
      INTEGER FUNCTION I15ADD(IA,IB)
      INTEGER IA,IB, ISUM
      ISUM = IAND(IA, 32767) + IAND(IB, 32767)
C     Oct 077777 = 32767 dec; carry bit 0100000 = 32768
      IF (ISUM .GE. 32768) ISUM = IAND(ISUM,32767) + 1
      I15ADD = IAND(ISUM,32767)
      RETURN
      END
C     AGC memory access
      INTEGER FUNCTION AGCRD(IADDR)
      INTEGER IADDR, EB, FB, IERAS, IFIXED, ICHAN
      INTEGER NERAS, NFIXED
      PARAMETER (NERAS=2048, NFIXED=36864)
      COMMON /AGCMEM/ IERAS(2048), IFIXED(36864), EB, FB, ICHAN(0:77)
      IF (IADDR .LT. 2048) THEN
         AGCRD = IERAS(IADDR+1)
      ELSE
         AGCRD = IFIXED(FB*1024 + (IADDR-2048) + 1)
      ENDIF
      RETURN
      END
      SUBROUTINE AGCWR(IADDR,IVAL,IERR)
      INTEGER IADDR,IVAL,IERR, EB, FB, IERAS, IFIXED, ICHAN
      PARAMETER (NERAS=2048, NFIXED=36864)
      COMMON /AGCMEM/ IERAS(2048), IFIXED(36864), EB, FB, ICHAN(0:77)
      IERR = 0
      IF (IADDR .LT. 2048) THEN
         IERAS(IADDR+1) = IAND(IVAL,32767)
      ELSE
         IERR = 2
      ENDIF
      RETURN
      END
      INTEGER FUNCTION CHRD(ICH)
      INTEGER ICH, IERAS, IFIXED, EB, FB, ICHAN
      PARAMETER (NERAS=2048, NFIXED=36864)
      COMMON /AGCMEM/ IERAS(2048), IFIXED(36864), EB, FB, ICHAN(0:77)
      CHRD = ICHAN(ICH)
      RETURN
      END
      SUBROUTINE CHWR(ICH,IVAL)
      INTEGER ICH,IVAL, IERAS, IFIXED, EB, FB, ICHAN
      PARAMETER (NERAS=2048, NFIXED=36864)
      COMMON /AGCMEM/ IERAS(2048), IFIXED(36864), EB, FB, ICHAN(0:77)
      ICHAN(ICH) = IAND(IVAL,32767)
      RETURN
      END
