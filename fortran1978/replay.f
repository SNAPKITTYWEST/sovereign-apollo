      CHARACTER*9 CMET
      COMMON /MSTATE/ IMETSC, IMETH(3), IVEH, IGUID, IENG, THRUST,
     *                ISP, THROTT, IENGON, ICOMM, POS(3), VEL(3),
     *                AMASS, AMDRY, CDU(3), IALARM, IPHASE(8)
      COMMON /MSTATC/ CMET
      COMMON /TELEM/ ICHKSUM, ILISTI, NWORDS
      IERR=0
      WRITE(IUNIT,'(A9,1X,I8,1X,I4,1X,I4,1X,F8.2,1X,I8,1X,3F7.1,1X,3F6.1,
     *1X,I2)', ERR=90) CMET, IMETSC, IVEH, IGUID, THROTT*1000.D0,
     *IALARM, POS(1)/1000.D0, POS(2)/1000.D0, POS(3)/1000.D0,
     *VEL(1), VEL(2), VEL(3), ICOMM
      RETURN
 90   IERR=1
      RETURN
      END
